// 조문 하나의 글 — long 이면 「헷갈릴 때」 묶음까지
export function articleText(a, { long = true } = {}) {
  const head = `${a.id} ${a.about}${a.layer ? ` [${a.layer}]` : ''}`
  if (a.id === 'R0') return [head, ...a.core].join('\n')
  return [head, '꼭:', ...expand(a.core), ...(long && a.aid.length ? ['헷갈릴 때:', ...a.aid] : []), ...(a.good ? [`예: ${a.good}`] : []), ...(a.bad ? [`반례: ${a.bad}`] : [])].join('\n')
}
// 룰 글 — 「생성 룰 N판」 머리 줄로 시작한다
export function genRulesText({ long = true, only = null } = {}) {
  const arts = only ? ARTICLES.filter((a) => only.includes(a.id)) : ARTICLES
  return [`생성 룰 ${GEN_RULES_REV}판`, PREAMBLE.join('\n'), ...arts.map((a) => articleText(a, { long }))].join('\n\n')
}
// 성격마다 머리 꼴 한 줄(룰 뒤에 따로 싣는다 · 모으는 갈래의 머리 꼴은 여전히 오류라 꼭 싣는다)
export const headLines = () => ['성격마다 항목 머리 꼴:', ...NATURES.map((n) => `- ${n}: ${FORMS[n].head}`)].join('\n')
// 프롬프트 · 스킬에 싣는 블록 — 룰 글 + 채널 덧붙임(닫힌 칸) + 머리 꼴
export function genRulesBlock({ profile = 'agent', heads = true } = {}) {
  const p = PROFILES[profile]
  if (!p) throw new Error(`모르는 생성 룰 덧붙임: ${profile}`)
  const add = [p.materials ? `재료: ${p.materials}` : '', p.output ? `내는 것: ${p.output}` : '', p.limits ? `한도: ${p.limits}` : ''].filter(Boolean)
  return [genRulesText({ long: p.rev === 'long', only: p.only || null }), ...(heads ? [headLines()] : []), ...(add.length ? [add.join('\n')] : [])].join('\n\n')
}
// 지문 — 긴 판 글의 sha256 앞 16자. 판 번호와 함께 측정 줄 · brief 에 실린다
export const rulesHash = () => createHash('sha256').update(genRulesText({ long: true })).digest('hex').slice(0, 16)
// 판마다 지문 — 글이 바뀌었는데 판이 그대로면 시험이 실패한다
export const GEN_RULES_HASH = { 1: 'ffad7271a047a232' }
// 조문 번호의 닫힌 목록 — 「R2」 · 「R2-1」 · 「R5-1」 (판단 칸의 rule · against 를 이 목록으로 거른다)
export function ruleIds() {
  const ids = new Set()
  for (const a of ARTICLES) {
    ids.add(a.id)
    for (const l of a.core) { const m = /^(\d)-(\d+) /.exec(l); if (m) ids.add(`R${m[1]}-${m[2]}`) }
  }
  return ids
}
export const isRuleId = (x) => ruleIds().has(String(x || '').trim().replace(/^r/, 'R'))
// 조문 제목 열 줄(brief 의 새 칸 · 스킬의 가리킴)
export const ruleTitles = () => ARTICLES.map((a) => `${a.id} ${a.about}`)
