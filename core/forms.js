// 문서의 종류 — 갈래 장부의 종류 · 서식 칸 · 없으면 이름으로 짐작(대장 · 회의 · 보고 · 결정)
//   → { kind, form(갈래 이름 · 없으면 null), props(대장 속성 · 없으면 null) }
export function kindOf(forms, docId) {
  const base = String(docId || '').split('/').pop()
  const f = forms ? formFor(forms, base) : null
  let kind
  if (f) kind = f.form === '결정기록' && f.kind !== '대장' ? '결정' : f.kind
  else kind = /대장$/.test(base) ? '대장' : /회의|미팅|면담|주간|월간|보고$|일지/.test(base) ? '사건' : /결정/.test(base) ? '결정' : '대상'
  const props = f?.props?.length ? f.props : kind === '대장' && /이슈|위험/.test(base) ? ISSUE_PROPS : null
  return { kind, form: f ? f.name : null, props }
}

// 프롬프트 블록 — WRITE_RULES 뒤에 짓는 문서의 계약 하나(4-8)
export function formBlock(kind, { name = '', props = null } = {}) {
  const F = FORMS[kind] || FORMS.대상
  return [
    `이 문서의 서식(${name ? name + ' · ' : ''}${kind}):`,
    `- 물음: ${F.ask}.`,
    `- 머리: ${F.head}.`,
    `- 첫 문장: ${F.lead}.`,
    `- 차례: ${F.order}.`,
    ...(props?.length ? [`- 속성 행(이 차례 · 빠짐 없이 · 빈 값 「-」): ${props.map((p) => p.name).join(' · ')}`] : []),
    ...(F.rules || []).map((r) => `- ${r}`),
    ...COMMON_RULES.map((r) => `- ${r}`),
    `좋은 예:\n${F.good}`,
    `나쁜 예: ${F.bad}`,
  ].join('\n')
}

// 고쳐 받기 꼴(같은 세션 · 4-8) — 걸린 줄만
export function formFixOf(xs) {
  return ['서식 검사에 걸린 곳이다. 걸린 곳만 고쳐 다시 낸다. 값은 바꾸지 않는다.', ...xs.slice(0, 12).map((x) => `- ${x.code}${x.where ? ` ${x.where}` : ''}${x.line ? ` ${x.line}째 줄` : ''}: ${x.msg}`)].join('\n')
}

// 템플릿 글 — 종류마다(docs/템플릿/*.md 와 같은 뼈대 · 시험이 둘을 견준다)
export function templateOf(kind) {
  const F = FORMS[kind] || FORMS.대상
  const labels = (F.labels || []).map((l) => `- **${l.name}**:${l.must ? '' : ' (선택)'}`).join('\n')
  return `# <갈래 이름>\n\n<요약 1~3문장: 이 문서가 무엇을 어떤 단위로 적나>\n\n## <${F.head.split('(')[0]}>\n\n<${F.lead}>\n${labels ? '\n' + labels + '\n' : ''}`
}
